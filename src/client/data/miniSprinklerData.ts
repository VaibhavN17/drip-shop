/** Generate 1 Acre set of KSR Excel items (only items that have quantity > 0 for 1 acre) */
export function get1AcreKsrItems(lang: "en" | "mr" = "en") {
  return KSR_EXCEL_ITEMS.filter((item) => item.oneAcreQty > 0).map((item) => ({
    description: lang === "mr" ? item.nameMr : item.nameEn,
    quantity: item.oneAcreQty,
    unit: item.unit,
    rate: item.price,
    gstRate: 5,
  }));
}

